package una.proyecto.datos;

import io.github.cdimascio.dotenv.Dotenv;
import io.github.cdimascio.dotenv.DotenvException;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;

public class Database {

    private static final String CONFIG_DIR = ".config";
    private static final String CONFIG_FILE = "database.env";
    private static final int VALIDATION_TIMEOUT_SECONDS = 2;

    private static Database theInstance;

    private final String url;
    private final String user;
    private final String password;
    private Connection cnx;

    public static synchronized Database instance() {
        if (theInstance == null) {
            theInstance = new Database();
        }
        return theInstance;
    }

    private Database() {
        Dotenv config;
        try {
            config = Dotenv.configure()
                    .directory(CONFIG_DIR)
                    .filename(CONFIG_FILE)
                    .ignoreIfMissing()
                    .load();
        } catch (DotenvException e) {
            throw new IllegalStateException(
                    "No se encontro " + CONFIG_DIR + "/" + CONFIG_FILE
                            + ". Copie database.env.example con ese nombre y complete sus datos.", e);
        }
        url = leerVariable(config, "DB_URL");
        user = leerVariable(config, "DB_USER");
        password = leerVariable(config, "DB_PASSWORD");
    }

    private static String leerVariable(Dotenv config, String nombre) {
        String valor = config.get(nombre);
        if (valor == null || valor.isBlank()) {
            throw new IllegalStateException(
                    "Falta la variable " + nombre + " en " + CONFIG_DIR + "/" + CONFIG_FILE);
        }
        return "DB_PASSWORD".equals(nombre) ? valor : valor.trim();
    }

    // Devuelve la conexion compartida. Los DAO NO deben cerrarla.
    public synchronized Connection getConnection() throws SQLException {
        if (cnx == null || !cnx.isValid(VALIDATION_TIMEOUT_SECONDS)) {
            if (cnx != null) {
                try {
                    cnx.close();
                } catch (SQLException ignored) {
                    // La conexion ya estaba muerta; se reemplaza abajo.
                }
            }
            cnx = DriverManager.getConnection(url, user, password);
        }
        return cnx;
    }

    public Connection openConnection() throws SQLException {
        return DriverManager.getConnection(url, user, password);
    }

    public PreparedStatement prepareStatement(String sql) throws SQLException {
        return getConnection().prepareStatement(sql);
    }

    // Para INSERT en tablas con AUTO_INCREMENT (categorias, reservas):
    // permite recuperar el id que genero MySQL.
    public  PreparedStatement prepareStatement(String sql, int autoGeneratedKeys)
            throws SQLException {
        return getConnection().prepareStatement(sql, autoGeneratedKeys);
    }

    public int executeUpdate(PreparedStatement statement) throws SQLException {
        return statement.executeUpdate();
    }

    public  ResultSet executeQuery(PreparedStatement statement) throws SQLException {
        return statement.executeQuery();
    }

    public  void close() throws SQLException {
        if (cnx != null && !cnx.isClosed()) {
            cnx.close();
        }
        cnx = null;
    }
}